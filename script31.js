/* =======================
   ZOOM + PAN
======================= */

let currentScale = 1;
let currentTranslate = { x: 0, y: 0 };
let isPanning = false;
let startPan = { x: 0, y: 0 };

const svgContainer = document.getElementById("svgContainer");
const svgWrapper = document.getElementById("svgWrapper");

function updateTransform() {
  if (!svgContainer) return;
  svgContainer.style.transform = `translate(${currentTranslate.x}px, ${currentTranslate.y}px) scale(${currentScale})`;
}

if (svgWrapper) {
  svgWrapper.addEventListener("wheel", e => {
    e.preventDefault();
    const delta = e.deltaY < 0 ? 0.1 : -0.1;
    currentScale = Math.min(2.5, Math.max(0.7, currentScale + delta));
    updateTransform();
  });

  svgWrapper.addEventListener("mousedown", e => {
    isPanning = true;
    startPan = { x: e.clientX - currentTranslate.x, y: e.clientY - currentTranslate.y };
  });
}

window.addEventListener("mousemove", e => {
  if (!isPanning) return;
  currentTranslate.x = e.clientX - startPan.x;
  currentTranslate.y = e.clientY - startPan.y;
  updateTransform();
});

window.addEventListener("mouseup", () => {
  isPanning = false;
});

